ok_count = 0
def ok(cond, msg):
    global ok_count
    if not cond:
        print('ECHEC :', msg); raise SystemExit(1)
    ok_count += 1
    print('  ok -', msg)

def shot(page, nom):
    if SHOTS: page.screenshot(path=os.path.join(SHOTS, nom + '.png'))

def etat(page, expr):
    return page.evaluate('() => { const E = window.__temps.E; return (' + expr + '); }')

def ouvrir(b, maint=MERCREDI, w=390, h=844, mouvement=True, init=None, chemin=''):
    ctx = b.new_context(viewport={'width': w, 'height': h}, device_scale_factor=2, is_mobile=True, has_touch=True,
                        reduced_motion=None if mouvement else 'reduce', accept_downloads=True)
    page = ctx.new_page()
    erreurs = []
    page.on('pageerror', lambda e: erreurs.append(str(e)))
    page.on('console', lambda m: erreurs.append('console: ' + m.text) if m.type == 'error' else None)
    page.erreurs = erreurs
    if init: page.add_init_script(init)
    page.goto(URL + '?maintenant=' + maint if maint else URL)
    page.wait_for_selector('.jour-nav')
    return ctx, page

def blocs(page):
    return page.evaluate("""() => [...document.querySelectorAll('.blocs .bl')].map(e => {
        const k = ['cours','ds','colle','event','bloc','vide'].find(c => e.classList.contains(c));
        const h = e.querySelectorAll('.heures span');
        return k + ' ' + h[0].textContent + '-' + h[1].textContent + ' ' + e.querySelector('b').textContent; })""")

def titre_jour(page): return page.inner_text('.jour-titre h1')
def pastilles(page): return page.inner_text('.pastilles')

def feuille(page): page.wait_for_selector('#calque:not([hidden]) .feuille')
def ferme(page): page.wait_for_selector('#calque', state='hidden')

def soumettre(page):
    page.click('[data-act=ok-form]'); ferme(page)

def onglet(page, v):
    page.click('[data-act=onglet][data-v=%s]' % v)

def jour_suivant(page, n=1):
    for _ in range(abs(n)): page.click('[data-act=jour][data-d="%d"]' % (1 if n > 0 else -1))

def aller_jour(page, iso):
    page.evaluate("(d) => { window.__temps.E.jour = d; window.__temps.E.vue = 'jour'; window.__temps.E.sous = null; window.__temps.rendre(true); }", iso)

def ajouter_bloc(page, nom, debut, fin, date=None):
    page.click('#fab'); feuille(page); page.click('[data-act=ajout-bloc]'); feuille(page)
    page.fill('[name=nom]', nom); page.fill('[name=debut]', debut); page.fill('[name=fin]', fin)
    if date: page.fill('[name=date]', date)
    soumettre(page)

def pas_de_debordement(page, quoi):
    ok(page.evaluate('() => document.documentElement.scrollWidth <= window.innerWidth + 1'), 'pas de défilement horizontal : ' + quoi)

